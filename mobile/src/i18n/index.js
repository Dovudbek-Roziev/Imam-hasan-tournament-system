let activeLanguage = 'ru';

// RU: Передать текущий язык мобильного приложения HTTP-клиенту.
// EN: Expose the current mobile language to the HTTP client.
export function getLanguage() { return activeLanguage; }


const LanguageContext = createContext({ language: 'ru', locale: 'ru-RU', t: (value) => value, toggleLanguage: () => {} });

// RU: Предоставить выбранный язык всем экранам приложения.
// EN: Provide the selected language to every application screen.
export function LanguageProvider({ children }) {
    const [language, setLanguage] = useState('ru');
    activeLanguage = language;
    const value = useMemo(() => ({
        language,
        locale: language === 'ky' ? 'ky-KG' : 'ru-RU',
        t: (value) => language === 'ky' ? (KY[value] || value) : value,
        toggleLanguage: () => setLanguage((current) => current === 'ru' ? 'ky' : 'ru'),
    }), [language]);
    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// RU: Получить переводчик и переключатель языка из контекста.
// EN: Read the translator and language switcher from context.
export function useLanguage() {
    return useContext(LanguageContext);
}
